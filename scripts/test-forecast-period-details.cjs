'use strict';
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const source=fs.readFileSync(fs.existsSync('assets/app.js')?'assets/app.js':'index.html','utf8');
const start=source.indexOf('const forecastPeriodNames='),end=source.indexOf('function renderRealWeather()',start);
assert.ok(start>=0&&end>start);
const run='2026-11-22T00:00:00Z',hour=3600000;
const models=[{model:'ICON-D2',run,rain:1},{model:'ICON-EU',run,rain:0},{model:'IFS',run,rain:0},{model:'GFS',run,rain:2}];
const frameVal=(f,id)=>f?.values?.[id]??NaN;
const context=vm.createContext({frameVal,frameHumidity:f=>frameVal(f,'rh2'),localFormat:(v,n=1)=>Number.isFinite(v)?String(+v.toFixed(n)):'—',forecastCandidates:()=>models,forecastPeriod:(point,start,now,end,d)=>({rain:d.rain}),modelProvider:m=>m.startsWith('ICON')?'DWD':m==='IFS'?'ECMWF':'NOAA',modelAgeLimit:()=>12,HOUR_MS:hour});
const freshStart=source.indexOf('// Fresh snowfall is an interval accumulation'),freshEnd=source.indexOf('function forecastPeriod(',freshStart);
assert.ok(freshStart>=0&&freshEnd>freshStart);
const snowApi=vm.runInContext(source.slice(freshStart,freshEnd)+'\n({newSnowInterval,periodNewSnow,periodNewSnowBounds,snowfallText,forecastPrecipText,hourlyNewSnowWindow,hourlySnowBoundsWindow,quantityRange})',context);
const close=(a,b)=>assert.ok(Math.abs(a-b)<1e-8,`${a} != ${b}`);
const snowData={},snowFrame=(i,values={})=>({d:snowData,hour:i,time:i*hour,values:{temp2:0,snowdepth:30,...values}});
const interval=(i,before,frame,amount=1)=>({start:i*hour,end:(i+1)*hour,hours:1,before,frame,amount});
const snowRows=Array.from({length:25},(_,i)=>snowFrame(i,{snowWaterTotal:i,ww:73,snowdepth:30-i/2}));
const snowIntervals=snowRows.slice(1).map((f,i)=>interval(i,snowRows[i],f));
const snowPeriods=Array.from({length:4},(_,i)=>({start:i*6*hour,end:(i+1)*6*hour,nativeIntervals:snowIntervals.slice(i*6,i*6+6)}));
close(snowApi.newSnowInterval(snowIntervals[0]),.7);
close(snowApi.periodNewSnow(snowPeriods[0]),4.2);
close(snowApi.periodNewSnow({periods:snowPeriods}),16.8); // snow cover shrinks, snowfall is still positive
close(snowApi.periodNewSnow({...snowPeriods[0],members:[snowPeriods[0],snowPeriods[1]]}),4.2);
close(snowApi.periodNewSnow({...snowPeriods[0],localHours:Array.from({length:6},()=>({newSnow:1}))}),6);
close(snowApi.periodNewSnow({...snowPeriods[0],localHours:[{newSnow:20}]}),4.2);
close(snowApi.hourlyNewSnowWindow([{start:0,end:hour,newSnow:1},{start:hour,end:2*hour,newSnow:3}],hour/2,hour*1.5),2);
assert.ok(Number.isNaN(snowApi.hourlyNewSnowWindow([{start:0,end:hour,newSnow:1}],hour/2,hour*1.5)));
assert.ok(Number.isNaN(snowApi.periodNewSnow({...snowPeriods[0],nativeIntervals:snowIntervals.slice(1,6)})));
close(snowApi.newSnowInterval(interval(0,snowFrame(0),snowFrame(1,{ww:73}),2)),1.4);
assert.equal(snowApi.newSnowInterval(interval(0,snowFrame(0),snowFrame(1,{ww:61}),2)),0);
assert.ok(Number.isNaN(snowApi.newSnowInterval(interval(0,snowFrame(0),snowFrame(1,{ww:68}),2))));
close(snowApi.newSnowInterval(interval(0,snowFrame(0,{snowGspTotal:0,snowConTotal:0}),snowFrame(1,{snowGspTotal:1,snowConTotal:1,ww:68}),3)),1.4);
const coarse={start:0,end:3*hour,hours:3,before:snowFrame(0,{snowWaterTotal:0}),frame:snowFrame(3,{snowWaterTotal:3}),amount:3};
close(snowApi.periodNewSnow({start:hour,end:2*hour,nativeIntervals:[coarse]}),.7);
assert.match(snowApi.forecastPrecipText({rain:1,newSnow:.7,weather:{icon:'21_schnee_2'}},'',true),/0–1 cm.*Neuschnee/);
assert.equal(snowApi.forecastPrecipText({rain:1,newSnow:0,weather:{icon:'11_regen_1'}}),'1–2 mm');
assert.equal(snowApi.forecastPrecipText({rain:1,newSnow:NaN,weather:{icon:'21_schnee_2'}}),'0–2 cm Neuschnee');
assert.equal(snowApi.forecastPrecipText({rain:NaN,newSnow:NaN,weather:{icon:'21_schnee_2'}}),'Menge unklar Neuschnee');
for(const [v,text] of [[0,'0 mm'],[.2,'0–1 mm'],[1.4,'1–2 mm'],[4.1,'2–5 mm'],[9.4,'5–10 mm'],[12,'10–20 mm'],[28,'20–50 mm'],[72,'50–100 mm']])assert.equal(snowApi.quantityRange(v),text);
const mixedInterval=interval(0,snowFrame(0),snowFrame(1,{ww:68}),1);
const uncertain={start:0,end:hour,rain:1,nativeIntervals:[mixedInterval]};
assert.deepEqual(Array.from(snowApi.periodNewSnowBounds(uncertain)),[0,1.6]);
const combined=snowApi.periodNewSnowBounds({periods:[uncertain,snowPeriods[0]]});close(combined[0],4.2);close(combined[1],5.8);
assert.equal(snowApi.snowfallText(combined),'2–10 cm');
assert.deepEqual(Array.from(snowApi.hourlySnowBoundsWindow([{start:0,end:hour,newSnowBounds:[0,2]},{start:hour,end:2*hour,newSnow:2}],hour/2,hour*1.5)),[1,2]);
const api=vm.runInContext(source.slice(start,end)+'\n({periodDetailMean,periodWindDirection,periodWetHours,periodPrecipChance,periodSnowfallWater})',context);
const d={},rows=Array.from({length:7},(_,i)=>({d,time:i*hour,values:{dew:-2+i,rh2:80,wind:15,winddir:i%2?10:350,snowWaterTotal:i*.5,pop:20+i*5}}));
const p={start:0,end:6*hour,duration:6,rain:3,rows,intervals:rows.slice(1).map((frame,i)=>({hours:1,frame,amount:i<3?1:0}))};
assert.equal(api.periodWetHours(p),3);
assert.equal(api.periodWetHours({...p,rain:0,intervals:[]}),0);
assert.ok(Number.isNaN(api.periodWetHours({...p,intervals:[{hours:6,amount:3}]})));
assert.ok(Number.isNaN(api.periodWetHours({...p,intervals:p.intervals.slice(1)})));
assert.equal(api.periodWetHours({...p,members:[p,{...p,rain:0}]}),1.5);
assert.equal(api.periodDetailMean(p,f=>frameVal(f,'dew')),1);
assert.equal(api.periodDetailMean(p,f=>frameVal(f,'rh2')),80);
assert.match(api.periodWindDirection(p),/^N · (0|360)°$/);
assert.equal(api.periodWindDirection({...p,rows:[],wind:1}),'Sehr schwacher Wind');
assert.equal(api.periodWindDirection({...p,rows:[],wind:20}),'Nicht verfügbar');
assert.equal(api.periodSnowfallWater(p),3);
assert.ok(Number.isNaN(api.periodSnowfallWater({...p,rows:[rows[0],{...rows[6],d:{}}]})));
assert.equal(api.periodPrecipChance(p,null,Date.parse(run)).value,'50 %');
const noPop={...p,intervals:p.intervals.map(r=>({...r,frame:{values:{}}}))};
const agreement=api.periodPrecipChance(noPop,null,Date.parse(run));
assert.equal(agreement.value,'2 von 3 · 67 %');
assert.match(agreement.note,/keine kalibrierte/);
assert.equal(api.periodPrecipChance(noPop,null,Date.parse(run)+24*hour).value,'—');
console.log('PASS: hourly wet duration, coarse/missing data, blended duration, humidity/dew, circular wind direction, snow water, new snow hourly/6 h/day and rain/mixed phase, true probability vs. model agreement');
