'use strict';
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const source=fs.readFileSync(fs.existsSync('assets/app.js')?'assets/app.js':'index.html','utf8');
const start=source.indexOf('const forecastPeriodNames='),end=source.indexOf('function renderRealWeather()',start);
assert.ok(start>=0&&end>start);
const run='2026-11-22T00:00:00Z',hour=3600000;
const models=[{model:'ICON-D2',run,rain:1},{model:'ICON-EU',run,rain:0},{model:'IFS',run,rain:0},{model:'GFS',run,rain:2}];
const frameVal=(f,id)=>f?.values?.[id]??NaN;
const context=vm.createContext({frameVal,frameHumidity:f=>frameVal(f,'rh2'),localFormat:(v,n=1)=>Number.isFinite(v)?String(+v.toFixed(n)):'—',forecastCandidates:()=>models,forecastPeriod:(point,start,now,end,d)=>({rain:d.rain}),modelProvider:m=>m.startsWith('ICON')?'DWD':m==='IFS'?'ECMWF':'NOAA',modelAgeLimit:()=>12,HOUR_MS:hour});
const api=vm.runInContext(source.slice(start,end)+'\n({periodDetailMean,periodWindDirection,periodWetHours,periodPrecipChance,periodSnowfallWater})',context);
const d={},rows=Array.from({length:7},(_,i)=>({d,time:i*hour,values:{dew:-2+i,rh2:80,wind:15,winddir:i%2?10:350,snowWaterTotal:i*.5,pop:20+i*5}}));
const p={start:0,end:6*hour,duration:6,rain:3,rows,intervals:rows.slice(1).map((frame,i)=>({hours:1,frame,amount:i<3?1:0}))};
assert.equal(api.periodWetHours(p),3);
assert.equal(api.periodWetHours({...p,rain:0,intervals:[]}),0);
assert.ok(Number.isNaN(api.periodWetHours({...p,intervals:[{hours:6,amount:3}]})));
assert.ok(Number.isNaN(api.periodWetHours({...p,intervals:p.intervals.slice(1)})));
assert.equal(api.periodWetHours({...p,members:[p,{...p,rain:0}]}),1.5);
assert.equal(api.periodDetailMean(p,f=>frameVal(f,'dew')),1);
assert.equal(api.periodDetailMean(p,f=>frameVal(f,'rh2')),80);
assert.match(api.periodWindDirection(p),/^N · (0|360)°$/);
assert.equal(api.periodSnowfallWater(p),3);
assert.ok(Number.isNaN(api.periodSnowfallWater({...p,rows:[rows[0],{...rows[6],d:{}}]})));
assert.equal(api.periodPrecipChance(p,null,Date.parse(run)).value,'50 %');
const noPop={...p,intervals:p.intervals.map(r=>({...r,frame:{values:{}}}))};
const agreement=api.periodPrecipChance(noPop,null,Date.parse(run));
assert.equal(agreement.value,'2 von 3 · 67 %');
assert.match(agreement.note,/keine kalibrierte/);
assert.equal(api.periodPrecipChance(noPop,null,Date.parse(run)+24*hour).value,'—');
console.log('PASS: hourly wet duration, coarse/missing data, blended duration, humidity/dew, circular wind direction, snow water, true probability vs. model agreement');
